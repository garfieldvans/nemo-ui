import type { CSSProperties, ReactElement, ReactNode } from "react";

export type TooltipPlacement = "top" | "right" | "bottom" | "left";

export interface TooltipProps {
  /** Isi panel tooltip. */
  content: ReactNode;
  /** Elemen trigger tunggal (button/link/dll). */
  children: ReactElement;
  /** Posisi default relatif terhadap trigger. Default "top". */
  placement?: TooltipPlacement;
  /** Delay muncul (ms). Default 100. */
  openDelay?: number;
  /** Delay hilang (ms). Default 50. */
  closeDelay?: number;
  /** Jarak panel dari trigger (px). Default 6. */
  offset?: number;
  /** Nonaktifkan tooltip (trigger tetap normal). Default false. */
  disabled?: boolean;
  /** Override id elemen tooltip (default: autogenerated). */
  id?: string;
  className?: string;
  style?: CSSProperties;
}